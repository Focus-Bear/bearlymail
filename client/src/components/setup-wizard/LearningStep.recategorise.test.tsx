import React from 'react';
import { fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import axios from 'axios';

import { LearningStep, pickPrimaryAction } from './LearningStep';

vi.mock('axios');
const mockedAxios = axios as jest.Mocked<typeof axios>;

vi.mock('react-i18next', () => ({
  Trans: ({ i18nKey }: { i18nKey: string }) => i18nKey,
  useTranslation: () => ({
    t: (key: string, params?: Record<string, unknown>) => (params ? `${key}:${JSON.stringify(params)}` : key),
  }),
}));

vi.mock('hooks/settings/useAnalysisProgress', () => ({
  useAnalysisProgress: () => ({
    analyzing: false,
    analyzeProgress: { show: true, progress: { current: 100, total: 100 }, error: null, isComplete: true },
    startAnalysis: vi.fn(),
    joinOrStartAnalysis: vi.fn(),
  }),
}));

const BATCH_ID = 'batch-1';
const NEW_CATEGORY = '🐞 Bug Reports';
const PRIMARY = 'learning-primary-action';
const CONTEXT = [
  { contextId: 'cat-1', contextKey: 'EMAIL_CATEGORY', contextValue: '🎧 Customer Support', source: 'AUTOGENERATED' },
];
const COUNTS = [
  { categoryId: 'cat-1', name: '🎧 Customer Support', count: 300 },
  { categoryId: 'cat-new', name: NEW_CATEGORY, count: 140 },
  { categoryId: null, name: null, count: 40 },
];

let jobProgress = { total: 480, completed: 120, failed: 0, pending: 360 };

function mockApi() {
  mockedAxios.get.mockImplementation(async (url: string) => {
    if (url.includes('/onboarding/categorisation-progress')) {
      return { data: { total: 480, categorised: 480 } };
    }
    if (url.includes('/onboarding/email-import-progress')) {
      return { data: { prioritizedCount: 480, isReady: true } };
    }
    if (url.includes('/onboarding/category-counts')) {
      return { data: COUNTS };
    }
    if (url.includes('/emails/recategorize-progress')) {
      return { data: jobProgress };
    }
    return { data: CONTEXT };
  });
  mockedAxios.post.mockImplementation(async (url: string) =>
    url.includes('/emails/recategorize-triage')
      ? { data: { batchId: BATCH_ID, queued: 480 } }
      : { data: { contextId: 'cat-new' } }
  );
}

async function addCategory(name: string) {
  const group = await screen.findByTestId('learned-group-categories');
  fireEvent.click(within(group).getByRole('button', { name: /groups\.categories\.add/ }));
  fireEvent.change(within(group).getByRole('textbox'), { target: { value: name } });
  fireEvent.click(within(group).getByRole('button', { name: 'setupWizard.learned.add' }));
}

describe('LearningStep — re-categorise after changing categories', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    jobProgress = { total: 480, completed: 120, failed: 0, pending: 360 };
    mockApi();
  });

  it('turns "Open my inbox" into "Re-categorise", shows live counts, then offers the inbox again', async () => {
    const onComplete = vi.fn();
    render(<LearningStep onComplete={onComplete} onBack={() => undefined} isLoading={false} />);
    await waitFor(() => expect(screen.getByTestId(PRIMARY)).toHaveTextContent('setupWizard.learning.openInbox'));

    await addCategory(NEW_CATEGORY);
    expect(screen.getByTestId(PRIMARY)).toHaveTextContent('setupWizard.recategorise.button');

    fireEvent.click(screen.getByTestId(PRIMARY));

    expect(mockedAxios.post).toHaveBeenCalledWith(expect.stringContaining('/emails/recategorize-triage'));
    await waitFor(() => expect(screen.getByTestId(PRIMARY)).toHaveTextContent('setupWizard.recategorise.running'));
    expect(screen.getByTestId(PRIMARY)).toBeDisabled();
    const panel = await screen.findByTestId('recategorise-panel');
    await waitFor(() => expect(within(panel).getByText(NEW_CATEGORY)).toBeInTheDocument());
    expect(within(panel).getByText('setupWizard.recategorise.other')).toBeInTheDocument();
    expect(onComplete).not.toHaveBeenCalled();

    jobProgress = { total: 480, completed: 478, failed: 2, pending: 0 };
    await waitFor(() => expect(screen.getByText('setupWizard.recategorise.doneTitle')).toBeInTheDocument(), {
      timeout: 5000,
    });
    expect(screen.getByTestId(PRIMARY)).toHaveTextContent('setupWizard.learning.openInbox');

    fireEvent.click(screen.getByTestId(PRIMARY));
    expect(onComplete).toHaveBeenCalledTimes(1);
  });

  it('leaves the button alone when only non-category items change', async () => {
    render(<LearningStep onComplete={() => undefined} onBack={() => undefined} isLoading={false} />);
    const projects = await screen.findByTestId('learned-group-projects');

    fireEvent.click(within(projects).getByRole('button', { name: /groups\.projects\.add/ }));
    fireEvent.change(within(projects).getByRole('textbox'), { target: { value: 'Ominio launch' } });
    fireEvent.click(within(projects).getByRole('button', { name: 'setupWizard.learned.add' }));

    await waitFor(() => expect(screen.getByTestId(PRIMARY)).toHaveTextContent('setupWizard.learning.openInbox'));
  });
});

describe('pickPrimaryAction', () => {
  const base = {
    canFinish: true,
    isLoading: false,
    hasUnsortedCategoryChanges: false,
    isRecategorising: false,
    onComplete: vi.fn(),
    onRecategorise: vi.fn(),
  };

  it('opens the inbox when nothing changed', () => {
    const action = pickPrimaryAction(base);
    expect(action.labelKey).toBe('setupWizard.learning.openInbox');
    expect(action.onClick).toBe(base.onComplete);
  });

  it('re-categorises after a category change, even before sorting finished', () => {
    const action = pickPrimaryAction({ ...base, canFinish: false, hasUnsortedCategoryChanges: true });
    expect(action).toMatchObject({ labelKey: 'setupWizard.recategorise.button', isEnabled: true });
    expect(action.onClick).toBe(base.onRecategorise);
  });

  it('is disabled while a re-sort runs', () => {
    expect(pickPrimaryAction({ ...base, isRecategorising: true }).isEnabled).toBe(false);
  });
});
