import React from 'react';
import { fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import axios from 'axios';

import { LearnedContextEditor } from './LearnedContextEditor';
import { INITIAL_VISIBLE_ITEMS } from './LearnedContextGroup';

vi.mock('axios');
const mockedAxios = axios as jest.Mocked<typeof axios>;

vi.mock('react-i18next', () => ({
  useTranslation: () => ({
    t: (key: string, params?: Record<string, unknown>) => (params ? `${key}:${JSON.stringify(params)}` : key),
  }),
}));

const CONTEXT = [
  { contextId: 'vip-1', contextKey: 'VIP_CONTACT', contextValue: 'Sarah Chen', source: 'AUTOGENERATED' },
  { contextId: 'cat-1', contextKey: 'EMAIL_CATEGORY', contextValue: '📰 Newsletters - Digests', source: 'AUTOGENERATED' },
  { contextId: 'qa-1', contextKey: 'Q_AND_A', contextValue: 'Pricing?', source: 'AUTOGENERATED' },
];

async function renderLoaded(context: unknown[] = CONTEXT) {
  mockedAxios.get.mockResolvedValue({ data: context });
  render(<LearnedContextEditor isEnabled />);
  await screen.findByTestId('learned-group-important');
}

describe('LearnedContextEditor', () => {
  beforeEach(() => {
    mockedAxios.put.mockResolvedValue({ data: {} });
    mockedAxios.delete.mockResolvedValue({ data: {} });
  });

  it('renders nothing and fetches nothing until analysis is complete', () => {
    render(<LearnedContextEditor isEnabled={false} />);

    expect(screen.queryByTestId('learned-context-editor')).not.toBeInTheDocument();
    expect(mockedAxios.get).not.toHaveBeenCalled();
  });

  it('groups learned items and shows an empty state with an add affordance for empty groups', async () => {
    await renderLoaded();

    expect(within(screen.getByTestId('learned-group-important')).getByText('Sarah Chen')).toBeInTheDocument();
    expect(within(screen.getByTestId('learned-group-categories')).getByText('📰 Newsletters')).toBeInTheDocument();
    expect(screen.queryByText('Pricing?')).not.toBeInTheDocument();

    const projects = screen.getByTestId('learned-group-projects');
    expect(within(projects).getByText('setupWizard.learned.groups.projects.empty')).toBeInTheDocument();
    expect(within(projects).getByRole('button', { name: /groups\.projects\.add/ })).toBeInTheDocument();
  });

  it('renames a category inline, keeping its description, via PUT /context/:id', async () => {
    await renderLoaded();

    fireEvent.click(screen.getByRole('button', { name: /editLabel.*📰 Newsletters/ }));
    const input = screen.getByRole('textbox');
    fireEvent.change(input, { target: { value: '📰 Reading list' } });
    fireEvent.keyDown(input, { key: 'Enter' });

    expect(await screen.findByText('📰 Reading list')).toBeInTheDocument();
    expect(mockedAxios.put).toHaveBeenCalledWith(expect.stringContaining('/context/cat-1'), {
      value: '📰 Reading list - Digests',
    });
  });

  it('removes an item via DELETE and restores it if the request fails', async () => {
    mockedAxios.delete.mockRejectedValueOnce(new Error('boom'));
    await renderLoaded();

    fireEvent.click(screen.getByRole('button', { name: /removeLabel.*Sarah Chen/ }));

    expect(mockedAxios.delete).toHaveBeenCalledWith(expect.stringContaining('/context/vip-1'));
    expect(await screen.findByText('Sarah Chen')).toBeInTheDocument();
    expect(screen.getByRole('alert')).toHaveTextContent('setupWizard.learned.saveError');
  });

  it('adds a new project as a USER_EDITED context row', async () => {
    mockedAxios.post.mockResolvedValue({ data: { contextId: 'proj-1' } });
    await renderLoaded();

    const projects = screen.getByTestId('learned-group-projects');
    fireEvent.click(within(projects).getByRole('button', { name: /groups\.projects\.add/ }));
    fireEvent.change(within(projects).getByRole('textbox'), { target: { value: 'Website relaunch' } });
    fireEvent.click(within(projects).getByRole('button', { name: 'setupWizard.learned.add' }));

    expect(await within(projects).findByText('Website relaunch')).toBeInTheDocument();
    expect(mockedAxios.post).toHaveBeenCalledWith(
      expect.stringContaining('/context'),
      expect.objectContaining({ contextKey: 'WORKING_ON', contextValue: 'Website relaunch', source: 'USER_EDITED' })
    );
    await waitFor(() =>
      expect(within(projects).getByRole('button', { name: /editLabel.*Website relaunch/ })).toBeEnabled()
    );
  });

  it('lets the user pick a VIP when adding to the mixed "important" group', async () => {
    mockedAxios.post.mockResolvedValue({ data: { contextId: 'vip-2' } });
    await renderLoaded();

    const important = screen.getByTestId('learned-group-important');
    fireEvent.click(within(important).getByRole('button', { name: /groups\.important\.add/ }));
    fireEvent.change(within(important).getByRole('combobox'), { target: { value: 'VIP_CONTACT' } });
    fireEvent.change(within(important).getByRole('textbox'), { target: { value: 'Marco Vitale' } });
    fireEvent.click(within(important).getByRole('button', { name: 'setupWizard.learned.add' }));

    await waitFor(() =>
      expect(mockedAxios.post).toHaveBeenCalledWith(
        expect.any(String),
        expect.objectContaining({ contextKey: 'VIP_CONTACT', contextValue: 'Marco Vitale' })
      )
    );
  });

  it('caps visible items and reveals the rest with "show more"', async () => {
    const manyCategories = Array.from({ length: INITIAL_VISIBLE_ITEMS + 3 }, (_, index) => ({
      contextId: `cat-${index}`,
      contextKey: 'EMAIL_CATEGORY',
      contextValue: `Category ${index}`,
    }));
    await renderLoaded(manyCategories);

    const categories = screen.getByTestId('learned-group-categories');
    expect(within(categories).getAllByRole('listitem')).toHaveLength(INITIAL_VISIBLE_ITEMS);

    fireEvent.click(within(categories).getByRole('button', { name: /showMore.*"count":3/ }));

    expect(within(categories).getAllByRole('listitem')).toHaveLength(INITIAL_VISIBLE_ITEMS + 3);
  });
});
