import { Repository } from "typeorm";

import {
  CategoryRule,
  CompositeCategoryRuleSpecV3,
} from "../database/entities/category-rule.entity";
import { CategoryRuleTombstone } from "../database/entities/category-rule-tombstone.entity";
import { compositeSpecWithinPositiveConditions } from "./category-rules-auto-composite.helper";
import {
  findTombstoneCoveringSpec,
  loadCategoryTombstones,
  loadDeletedRuleCheck,
  recordTombstoneForDeletedRule,
} from "./category-rules-tombstone.helper";

const USER_ID = "user-1";
const CATEGORY_ID = "cat-releases";

const spec = (
  overrides: Partial<CompositeCategoryRuleSpecV3> = {},
): CompositeCategoryRuleSpecV3 => ({
  v: 3,
  fromMatchesAny: ["releases@acme.com", "deploys@acme.com"],
  subjectContainsAny: ["Released", "Deployed"],
  bodyContainsAny: [],
  ...overrides,
});

const tombstone = (
  compositeSpec: CompositeCategoryRuleSpecV3,
): CategoryRuleTombstone =>
  ({
    id: "tomb-1",
    userId: USER_ID,
    categoryId: CATEGORY_ID,
    compositeSpec,
    deletedRuleId: "deleted-rule",
  }) as CategoryRuleTombstone;

const rule = (overrides: Partial<CategoryRule> = {}): CategoryRule =>
  ({
    id: "rule-1",
    userId: USER_ID,
    categoryId: CATEGORY_ID,
    ruleKind: "composite",
    compositeSpec: spec(),
    isAutoGenerated: true,
    ...overrides,
  }) as CategoryRule;

function fakeTombstoneRepository(existing: CategoryRuleTombstone[] = []) {
  const repository = {
    find: jest.fn().mockResolvedValue(existing),
    create: jest.fn((row: Partial<CategoryRuleTombstone>) => row),
    save: jest.fn((row: Partial<CategoryRuleTombstone>) =>
      Promise.resolve(row),
    ),
  };
  return {
    repository,
    typed: repository as unknown as Repository<CategoryRuleTombstone>,
  };
}

describe("compositeSpecWithinPositiveConditions", () => {
  it("is true for the same rule, ignoring case and order", () => {
    const candidate = spec({
      fromMatchesAny: ["DEPLOYS@acme.com", "releases@acme.com"],
      subjectContainsAny: ["deployed", "released"],
    });
    expect(compositeSpecWithinPositiveConditions(spec(), candidate)).toBe(true);
  });

  it("is true for a narrower candidate (fewer senders and phrases)", () => {
    const candidate = spec({
      fromMatchesAny: ["releases@acme.com"],
      subjectContainsAny: ["Released"],
    });
    expect(compositeSpecWithinPositiveConditions(spec(), candidate)).toBe(true);
  });

  it("ignores exclusions on either side", () => {
    const deleted = spec({ subjectNotContainsAny: ["weekly digest"] });
    const candidate = spec({
      subjectNotContainsAny: ["rollback"],
      bodyNotContainsAny: ["unsubscribe"],
    });
    expect(compositeSpecWithinPositiveConditions(deleted, candidate)).toBe(
      true,
    );
  });

  it("is false when the candidate adds a sender", () => {
    const candidate = spec({
      fromMatchesAny: ["releases@acme.com", "builds@acme.com"],
    });
    expect(compositeSpecWithinPositiveConditions(spec(), candidate)).toBe(
      false,
    );
  });

  it("is false when the candidate drops the subject constraint (empty matches any subject)", () => {
    const candidate = spec({ subjectContainsAny: [] });
    expect(compositeSpecWithinPositiveConditions(spec(), candidate)).toBe(
      false,
    );
  });

  it("is true for a candidate pinned to a refinement of the deleted rule's sub-stream", () => {
    const deleted = spec({ notificationSubtype: "github:pr" });
    const candidate = spec({ notificationSubtype: "github:pr:comment:human" });
    expect(compositeSpecWithinPositiveConditions(deleted, candidate)).toBe(
      true,
    );
  });

  it("is false for a candidate pinned to a different sub-stream", () => {
    const deleted = spec({ notificationSubtype: "github:pr" });
    const candidate = spec({ notificationSubtype: "github:issue" });
    expect(compositeSpecWithinPositiveConditions(deleted, candidate)).toBe(
      false,
    );
  });

  it("is false when the candidate pins different GitHub facts", () => {
    const candidate = spec({ githubStateAny: ["merged"] });
    expect(compositeSpecWithinPositiveConditions(spec(), candidate)).toBe(
      false,
    );
  });
});

describe("findTombstoneCoveringSpec", () => {
  it("returns the tombstone that covers the candidate", () => {
    const covering = tombstone(spec());
    expect(
      findTombstoneCoveringSpec(
        [tombstone(spec({ fromMatchesAny: ["other@acme.com"] })), covering],
        spec({ fromMatchesAny: ["releases@acme.com"] }),
      ),
    ).toBe(covering);
  });

  it("returns null when no tombstone covers the candidate", () => {
    expect(
      findTombstoneCoveringSpec(
        [tombstone(spec({ fromMatchesAny: ["releases@acme.com"] }))],
        spec(),
      ),
    ).toBeNull();
  });
});

describe("loadDeletedRuleCheck", () => {
  const loadCheck = (existing: CategoryRuleTombstone[]) => {
    const logger = { log: jest.fn() };
    const { typed } = fakeTombstoneRepository(existing);
    const check = loadDeletedRuleCheck({
      repository: typed,
      logger,
      userId: USER_ID,
      categoryId: CATEGORY_ID,
      categoryName: "Releases",
    });
    return { logger, check };
  };

  it("logs and reports a candidate a deleted rule covers", async () => {
    const { logger, check } = loadCheck([tombstone(spec())]);

    expect((await check)(spec())).toBe(true);
    expect(logger.log).toHaveBeenCalledWith(
      expect.stringContaining("deleted rule deleted-rule"),
    );
  });

  it("passes a candidate no deleted rule covers, without logging", async () => {
    const { logger, check } = loadCheck([]);

    expect((await check)(spec())).toBe(false);
    expect(logger.log).not.toHaveBeenCalled();
  });
});

describe("loadCategoryTombstones", () => {
  it("skips the query when the category is unknown", async () => {
    const { repository, typed } = fakeTombstoneRepository();
    await expect(loadCategoryTombstones(typed, USER_ID, null)).resolves.toEqual(
      [],
    );
    expect(repository.find).not.toHaveBeenCalled();
  });

  it("loads the user's tombstones for the category", async () => {
    const { repository, typed } = fakeTombstoneRepository();
    await loadCategoryTombstones(typed, USER_ID, CATEGORY_ID);
    expect(repository.find).toHaveBeenCalledWith({
      where: { userId: USER_ID, categoryId: CATEGORY_ID },
    });
  });
});

describe("recordTombstoneForDeletedRule", () => {
  it("records the spec of a deleted auto-generated composite rule", async () => {
    const { repository, typed } = fakeTombstoneRepository();
    const deleted = rule();

    await recordTombstoneForDeletedRule(typed, deleted);

    expect(repository.save).toHaveBeenCalledWith({
      userId: USER_ID,
      categoryId: CATEGORY_ID,
      compositeSpec: deleted.compositeSpec,
      deletedRuleId: deleted.id,
    });
  });

  it.each([
    ["a user-created rule", { isAutoGenerated: false }],
    ["a legacy rule", { ruleKind: "legacy" as const, compositeSpec: null }],
    ["a rule with no category", { categoryId: null }],
  ])("records nothing for %s", async (_label, overrides) => {
    const { repository, typed } = fakeTombstoneRepository();

    await expect(
      recordTombstoneForDeletedRule(typed, rule(overrides)),
    ).resolves.toBeNull();
    expect(repository.save).not.toHaveBeenCalled();
  });

  it("records nothing when an earlier tombstone already covers the rule", async () => {
    const { repository, typed } = fakeTombstoneRepository([tombstone(spec())]);

    await recordTombstoneForDeletedRule(
      typed,
      rule({ compositeSpec: spec({ fromMatchesAny: ["releases@acme.com"] }) }),
    );

    expect(repository.save).not.toHaveBeenCalled();
  });
});
