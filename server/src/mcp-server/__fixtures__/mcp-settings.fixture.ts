/** Both fakes answer per user, like the real services' `WHERE userId = $1`. */
export function settingsServiceMocks() {
  const contextService: MockedContextService = {
    getUserContext: jest.fn(
      async (userId: string) => CONTEXTS_BY_USER[userId] ?? [],
    ),
    createOrUpdateContext: jest.fn(
      async (
        userId: string,
        contextKey: ContextKey,
        contextValue: string,
        source: Source,
      ) =>
        ({
          userId,
          contextId: "77777777-7777-4777-8777-777777777777",
          contextKey,
          contextValue,
          source,
        }) as UserContext,
    ),
    updateContext: jest.fn(
      async (
        contextId: string,
        userId: string,
        updates: Partial<UserContext>,
      ) => {
        const row = CONTEXTS_BY_USER[userId]?.find(
          (candidate) => candidate.contextId === contextId,
        );
        return row ? { ...row, ...updates, source: Source.USER_EDITED } : null;
      },
    ),
    deleteContext: jest.fn().mockResolvedValue(undefined),
  };
  const categoryRulesService: MockedCategoryRulesService = {
    listRules: jest.fn(async (userId: string) => RULES_BY_USER[userId] ?? []),
    createCompositeRule: jest.fn(),
    updateCategoryRule: jest.fn(),
    deleteRule: jest.fn().mockResolvedValue(true),
  };
  const auditLogs = {
    create: jest.fn((entry: unknown) => entry),
    save: jest.fn().mockResolvedValue(undefined),
  };
  return {
    contextService,
    categoryRulesService,
    auditLogs,
    asContextService: contextService as unknown as ContextService,
    asCategoryRulesService:
      categoryRulesService as unknown as CategoryRulesService,
  };
}

