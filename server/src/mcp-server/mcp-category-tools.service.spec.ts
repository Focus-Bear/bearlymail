import { Repository } from "typeorm";

import { AuditLog } from "../database/entities/audit-log.entity";
import { ContextKey, Source } from "../database/entities/user-context.entity";
import {
  BUG_RULE_ID,
  BUGS_ID,
  callContext,
  LEGACY_RULE_ID,
  OTHER_USER,
  OTHER_USERS_CATEGORY_ID,
  OWNER,
  QA_PASSED_ID,
  QA_RULE_ID,
  SETTINGS_AUDIT,
  settingsServiceMocks,
  VIP_CONTEXT_ID,
} from "./__fixtures__/mcp-settings.fixture";
import { McpCategoryToolsService } from "./mcp-category-tools.service";
import { McpToolInputError } from "./mcp-tool-args";

describe("McpCategoryToolsService", () => {
  let mocks: ReturnType<typeof settingsServiceMocks>;
  let service: McpCategoryToolsService;

  beforeEach(() => {
    mocks = settingsServiceMocks();
    service = new McpCategoryToolsService(
      mocks.asContextService,
      mocks.asCategoryRulesService,
      mocks.auditLogs as unknown as Repository<AuditLog>,
    );
  });

  describe("listCategories", () => {
    it("lists only the caller's email categories, with rule counts", async () => {
      const result = await service.listCategories(callContext(OWNER));

      expect(mocks.contextService.getUserContext).toHaveBeenCalledWith(OWNER);
      expect(result.count).toBe(2);
      expect(result.categories).toEqual([
        {
          categoryId: QA_PASSED_ID,
          name: "✅ Github QA passed issues",
          description: "QA comments saying Pass",
          source: Source.AUTOGENERATED,
          ruleCount: 1,
          enabledRuleCount: 1,
        },
        expect.objectContaining({
          categoryId: BUGS_ID,
          description: null,
          ruleCount: 2,
          enabledRuleCount: 1,
        }),
      ]);
      expect(JSON.stringify(result)).not.toContain(VIP_CONTEXT_ID);
    });
  });

  describe("getCategory", () => {
    it("returns the category with its rules in MCP field names", async () => {
      const result = await service.getCategory(callContext(OWNER), {
        categoryId: QA_PASSED_ID,
      });
      expect(result.rules).toHaveLength(1);
      expect(result.rules[0]).toMatchObject({
        ruleId: QA_RULE_ID,
        categoryExists: true,
        conditions: {
          fromMatchesAny: ["notifications@github.com"],
          bodyNotContainsAny: ["Fail"],
        },
      });
    });

    it("can't read another user's category (owner control: they can)", async () => {
      await expect(
        service.getCategory(callContext(OTHER_USER), {
          categoryId: OTHER_USERS_CATEGORY_ID,
        }),
      ).resolves.toMatchObject({
        category: { categoryId: OTHER_USERS_CATEGORY_ID },
      });
      await expect(
        service.getCategory(callContext(OWNER), {
          categoryId: OTHER_USERS_CATEGORY_ID,
        }),
      ).rejects.toThrow(`No category found with id ${OTHER_USERS_CATEGORY_ID}`);
    });

    it("won't treat a non-category context row (a VIP contact) as a category", async () => {
      await expect(
        service.getCategory(callContext(OWNER), { categoryId: VIP_CONTEXT_ID }),
      ).rejects.toBeInstanceOf(McpToolInputError);
    });

    it("rejects an id that isn't a UUID", async () => {
      await expect(
        service.getCategory(callContext(OWNER), { categoryId: "QA" }),
      ).rejects.toThrow("`categoryId` must be a BearlyMail id");
    });
  });

  describe("createCategory", () => {
    it("creates a user-edited category in the stored 'Name - Description' form and audits it", async () => {
      const result = await service.createCategory(callContext(OWNER), {
        name: "  Release notes ",
        description: "App store release announcements",
      });

      expect(mocks.contextService.createOrUpdateContext).toHaveBeenCalledWith(
        OWNER,
        ContextKey.EMAIL_CATEGORY,
        "Release notes - App store release announcements",
        Source.USER_EDITED,
      );
      expect(result.created).toMatchObject({
        name: "Release notes",
        description: "App store release announcements",
      });
      expect(mocks.auditLogs.save).toHaveBeenCalledWith(
        expect.objectContaining({
          userId: OWNER,
          action: SETTINGS_AUDIT.CATEGORY_CREATED,
        }),
      );
    });

    it("refuses a duplicate name, ignoring case and emoji", async () => {
      await expect(
        service.createCategory(callContext(OWNER), {
          name: "github qa PASSED issues",
        }),
      ).rejects.toThrow(`categoryId ${QA_PASSED_ID}`);
      expect(mocks.contextService.createOrUpdateContext).not.toHaveBeenCalled();
    });

    it("refuses a name containing the name/description separator", async () => {
      await expect(
        service.createCategory(callContext(OWNER), { name: "Bills - urgent" }),
      ).rejects.toBeInstanceOf(McpToolInputError);
    });

    it("only checks duplicates among the caller's categories", async () => {
      await service.createCategory(callContext(OWNER), {
        name: "Their private category",
      });
      expect(mocks.contextService.createOrUpdateContext).toHaveBeenCalled();
    });
  });

  describe("updateCategory", () => {
    it("renames, keeps the description, and returns before and after", async () => {
      const result = await service.updateCategory(callContext(OWNER), {
        categoryId: QA_PASSED_ID,
        name: "QA Passed",
      });
      expect(mocks.contextService.updateContext).toHaveBeenCalledWith(
        QA_PASSED_ID,
        OWNER,
        { contextValue: "QA Passed - QA comments saying Pass" },
      );
      expect(result.before.name).toBe("✅ Github QA passed issues");
      expect(result.after.name).toBe("QA Passed");
    });

    it("clears the description when passed null", async () => {
      await service.updateCategory(callContext(OWNER), {
        categoryId: QA_PASSED_ID,
        description: null,
      });
      expect(mocks.contextService.updateContext).toHaveBeenCalledWith(
        QA_PASSED_ID,
        OWNER,
        { contextValue: "✅ Github QA passed issues" },
      );
    });

    it("can't change another user's category", async () => {
      await expect(
        service.updateCategory(callContext(OWNER), {
          categoryId: OTHER_USERS_CATEGORY_ID,
          name: "Mine now",
        }),
      ).rejects.toBeInstanceOf(McpToolInputError);
      expect(mocks.contextService.updateContext).not.toHaveBeenCalled();
    });

    it("needs something to change and refuses an empty or clashing name", async () => {
      const owner = callContext(OWNER);
      await expect(
        service.updateCategory(owner, { categoryId: QA_PASSED_ID }),
      ).rejects.toThrow("Pass `name` and/or `description`");
      await expect(
        service.updateCategory(owner, { categoryId: QA_PASSED_ID, name: " " }),
      ).rejects.toThrow("`name` can't be empty");
      await expect(
        service.updateCategory(owner, {
          categoryId: QA_PASSED_ID,
          name: "Human-reported bug issues",
        }),
      ).rejects.toThrow("already exists");
      expect(mocks.contextService.updateContext).not.toHaveBeenCalled();
    });
  });

  describe("deleteCategory", () => {
    it("dry run lists the rules that would lose their category and deletes nothing", async () => {
      const result = await service.deleteCategory(callContext(OWNER), {
        categoryId: BUGS_ID,
        dryRun: true,
      });
      expect(result.dryRun).toBe(true);
      expect(
        result.wouldDelete?.rulesLeftWithoutACategory.map(
          (rule) => rule.ruleId,
        ),
      ).toEqual([BUG_RULE_ID, LEGACY_RULE_ID]);
      expect(mocks.contextService.deleteContext).not.toHaveBeenCalled();
      expect(mocks.auditLogs.save).not.toHaveBeenCalled();
    });

    it("deletes the caller's category and audits what was removed", async () => {
      const result = await service.deleteCategory(callContext(OWNER), {
        categoryId: QA_PASSED_ID,
      });
      expect(mocks.contextService.deleteContext).toHaveBeenCalledWith(
        QA_PASSED_ID,
        OWNER,
      );
      expect(result.deleted?.category.name).toBe("✅ Github QA passed issues");
      expect(mocks.auditLogs.save).toHaveBeenCalledWith(
        expect.objectContaining({
          action: SETTINGS_AUDIT.CATEGORY_DELETED,
          targetId: QA_PASSED_ID,
          metadata: expect.objectContaining({ ruleIds: [QA_RULE_ID] }),
        }),
      );
    });

    it("can't delete another user's category (owner control: they can)", async () => {
      await expect(
        service.deleteCategory(callContext(OWNER), {
          categoryId: OTHER_USERS_CATEGORY_ID,
        }),
      ).rejects.toBeInstanceOf(McpToolInputError);
      expect(mocks.contextService.deleteContext).not.toHaveBeenCalled();

      await service.deleteCategory(callContext(OTHER_USER), {
        categoryId: OTHER_USERS_CATEGORY_ID,
      });
      expect(mocks.contextService.deleteContext).toHaveBeenCalledWith(
        OTHER_USERS_CATEGORY_ID,
        OTHER_USER,
      );
    });
  });
});
