/** A composite rule's match conditions, in the field names create/update_rule accept. */
export type McpRuleConditions = Omit<CompositeCategoryRuleSpecV3, "v">;

export interface McpCategoryView {
  categoryId: string;
  name: string;
  description: string | null;
  /** AUTOGENERATED (learned by BearlyMail) or USER_EDITED. */
  source: string;
  ruleCount: number;
  enabledRuleCount: number;
}

export interface McpRuleView {
  ruleId: string;
  categoryId: string | null;
  categoryName: string;
  /** False when the rule's category was deleted: the rule can never match. */
  categoryExists: boolean;
  kind: CategoryRuleDto["ruleKind"];
  isEnabled: boolean;
  /** How many emails this rule has categorised. */
  hitCount: number;
  /** Composite rules only. */
  conditions: McpRuleConditions | null;
  /** Legacy (auto-learned, hash-based) rules only; they can't be edited, only toggled, moved or deleted. */
  legacyMatch: {
    type: CategoryRuleDto["ruleType"];
    pattern: string;
    subjectPrefix: string | null;
  } | null;
  /** The AI review an auto-generated rule passed, if any. */
  autoReview: { verdict: string; reason: string } | null;
  createdAt: Date;
  updatedAt: Date;
}

export interface McpCategory {
  categoryId: string;
  name: string;
  description: string | null;
  source: string;
}

/** Spec v1/v2/v3 all come out in the v3 field names, so what Claude reads it can write back. */
export function toRuleConditions(
  spec: CompositeCategoryRuleSpec,
): McpRuleConditions {
  const { senderMatchesAny, v: _version, ...phrases } = specToV2(spec);
  return {
    fromMatchesAny: senderMatchesAny,
    ...phrases,
    ...copyV3ExtraFields(spec),
  };
}

export function toCategory(row: UserContext): McpCategory {
  const { name, description } = parseCategoryValue(row.contextValue);
  return {
    categoryId: row.contextId,
    name,
    description,
    source: row.source,
  };
}

/** The stored "Name - Description" form of a category. */
export function toCategoryValue(
  name: string,
  description: string | null | undefined,
): string {
  const trimmedName = name.trim();
  const trimmedDescription = description?.trim();
  return trimmedDescription
    ? `${trimmedName}${MCP_SETTINGS.CATEGORY_VALUE_SEPARATOR}${trimmedDescription}`
    : trimmedName;
}

export function filterCategories(rows: UserContext[]): McpCategory[] {
  return rows
    .filter((row) => row.contextKey === ContextKey.EMAIL_CATEGORY)
    .map(toCategory);
}

export function toCategoryView(
  category: McpCategory,
  rules: CategoryRuleDto[],
): McpCategoryView {
  const own = rules.filter((rule) => rule.categoryId === category.categoryId);
  return {
    ...category,
    ruleCount: own.length,
    enabledRuleCount: own.filter((rule) => rule.isEnabled).length,
  };
}

export function toRuleView(
  rule: CategoryRuleDto,
  categoriesById: ReadonlyMap<string, McpCategory>,
): McpRuleView {
  const category = rule.categoryId
    ? categoriesById.get(rule.categoryId)
    : undefined;
  return {
    ruleId: rule.id,
    categoryId: rule.categoryId,
    categoryName: category?.name ?? rule.categoryName,
    categoryExists: category !== undefined,
    kind: rule.ruleKind,
    isEnabled: rule.isEnabled,
    hitCount: rule.hitCount,
    conditions: rule.compositeSpec
      ? toRuleConditions(rule.compositeSpec)
      : null,
    legacyMatch: rule.compositeSpec
      ? null
      : {
          type: rule.ruleType,
          pattern: rule.pattern,
          subjectPrefix: rule.subjectPrefix,
        },
    autoReview: rule.sanityCheck
      ? { verdict: rule.sanityCheck.verdict, reason: rule.sanityCheck.reason }
      : null,
    createdAt: rule.createdAt,
    updatedAt: rule.updatedAt,
  };
}

/** Looks only among the caller's own categories, so another user's id reads as "not found". */
export function findCategory(
  categories: McpCategory[],
  categoryId: string,
): McpCategory {
  const category = categories.find(
    (candidate) => candidate.categoryId === categoryId,
  );
  if (!category) {
    throw new McpToolInputError(`No category found with id ${categoryId}`);
  }
  return category;
}

export function indexCategories(
  categories: McpCategory[],
): Map<string, McpCategory> {
  return new Map(categories.map((category) => [category.categoryId, category]));
}

interface SettingsAuditEntry {
  action: McpSettingsAuditAction;
  targetType: McpSettingsAuditTargetType;
  targetId: string | null;
  /** Encrypted at rest; holds the before/after values so a change can be undone by hand. */
  details: Record<string, unknown>;
}

/** Every settings change made through MCP is audited, like MCP sends. */
export async function recordSettingsAudit(
  auditLogs: Repository<AuditLog>,
  context: McpCallContext,
  entry: SettingsAuditEntry,
): Promise<void> {
  const { userId, tokenId } = context.principal;
  await auditLogs.save(
    auditLogs.create({
      userId,
      action: entry.action,
      targetType: entry.targetType,
      targetId: entry.targetId,
      metadata: { tokenId, ...entry.details },
      ipAddress: context.ipAddress,
      userAgent: context.userAgent,
    }),
  );
}
